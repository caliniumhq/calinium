'use strict';

const fs = require('fs');
const path = require('path');
const { createSchemaValidator } = require('../compiler/schema-validator');
const { validateApprovedDeploymentPackage } = require('../deployment/deployment-validator');
const { fileHash } = require('../deployment/utils');
const { assertReviewSessionPath } = require('../review-engine/utils');
const { assertDeploymentPath, result, resultOrigin, same, relative, readRequiredJson } = require('./utils');

function readArtifacts(root, deploymentPath) {
  const artifacts = {
    packagePath: path.join(deploymentPath, 'manifests/deployment-package.json'),
    deploymentReportPath: path.join(deploymentPath, 'reports/deployment-report.json'),
    previewReportPath: path.join(deploymentPath, 'reports/preview-report.json'),
    rollbackPath: path.join(deploymentPath, 'reports/rollback-metadata.json'),
    snapshotDirectory: path.join(deploymentPath, 'verification/uploaded-configuration')
  };
  const errors = [];
  for (const [key, label] of [['packagePath', 'Deployment package'], ['deploymentReportPath', 'Deployment report'], ['previewReportPath', 'Preview report'], ['rollbackPath', 'Rollback metadata']]) {
    try { artifacts[key.replace('Path', '')] = readRequiredJson(artifacts[key], label); } catch (error) { errors.push(error.message); }
  }
  if (!fs.existsSync(artifacts.snapshotDirectory)) errors.push('Post-upload configuration snapshot is missing.');
  return { artifacts, errors };
}

function schemaResult(root, object, schema, id, category, origin) {
  const errors = createSchemaValidator(root).validateFile(object, schema, id.replace(/:/g, '_'));
  return result({ id, category, method: 'json_schema_validation', expected: `valid ${schema}`, actual: errors.length ? errors : 'valid', passed: errors.length === 0, remediation: 'Restore the canonical immutable deployment artifact generated by the preceding Calinium layer.', origin });
}

function verifyDeployment({ root, deploymentPath }) {
  const resolved = assertDeploymentPath(root, deploymentPath);
  const loaded = readArtifacts(root, resolved);
  if (loaded.errors.length) return { ready: false, errors: loaded.errors, warnings: [], results: [], deploymentPath: resolved };
  const { artifacts } = loaded;
  const packageData = artifacts.package;
  const deploymentRecord = artifacts.deploymentReport;
  const previewReport = artifacts.previewReport;
  const rollback = artifacts.rollback;
  const validator = createSchemaValidator(root);
  const artifactSchemaErrors = [
    ...validator.validateFile(packageData, 'schemas/calinium-deployment-package.schema.json', 'deployment_package'),
    ...validator.validateFile(deploymentRecord, 'schemas/calinium-deployment-record.schema.json', 'deployment_record'),
    ...validator.validateFile(previewReport, 'schemas/calinium-preview-report.schema.json', 'preview_report'),
    ...validator.validateFile(rollback, 'schemas/calinium-rollback-metadata.schema.json', 'rollback_metadata')
  ];
  if (artifactSchemaErrors.length) return { ready: false, errors: artifactSchemaErrors.map((error) => `Deployment evidence schema failure: ${error}`), warnings: [], results: [], deploymentPath: resolved };
  let sessionPath;
  try {
    sessionPath = path.resolve(root, packageData.review_session);
    const canonical = assertReviewSessionPath(root, path.basename(sessionPath));
    if (canonical !== sessionPath) throw new Error('Deployment package review-session path is not canonical.');
  } catch (error) {
    return { ready: false, errors: [`Deployment package review-session reference is invalid: ${error.message}`], warnings: [], results: [], deploymentPath: resolved };
  }
  const origin = resultOrigin({ deploymentId: deploymentRecord.deployment_id || path.basename(resolved), reviewSession: packageData.review_session, approvalManifest: packageData.approval_manifest, generatedFile: packageData.generated_theme_manifest });
  const results = [
    schemaResult(root, packageData, 'schemas/calinium-deployment-package.schema.json', 'deployment:package-schema', 'deployment', origin),
    schemaResult(root, deploymentRecord, 'schemas/calinium-deployment-record.schema.json', 'deployment:record-schema', 'deployment', origin),
    schemaResult(root, previewReport, 'schemas/calinium-preview-report.schema.json', 'deployment:preview-schema', 'preview', origin),
    schemaResult(root, rollback, 'schemas/calinium-rollback-metadata.schema.json', 'deployment:rollback-schema', 'deployment', origin),
    result({ id: 'deployment:id', category: 'deployment', method: 'directory_identifier_comparison', expected: path.basename(resolved), actual: deploymentRecord.deployment_id, passed: deploymentRecord.deployment_id === path.basename(resolved), remediation: 'Use a deployment record whose ID matches its immutable deployment directory.', origin }),
    result({ id: 'deployment:status', category: 'deployment', method: 'deployment_status_check', expected: 'deployed_to_development_theme', actual: deploymentRecord.status, passed: deploymentRecord.status === 'deployed_to_development_theme', remediation: 'Only successfully deployed development-theme records can be preview verified.', origin }),
    result({ id: 'deployment:package', category: 'deployment', method: 'package_identifier_comparison', expected: packageData.package_id, actual: deploymentRecord.package?.package_id, passed: deploymentRecord.package?.package_id === packageData.package_id, remediation: 'Restore the deployment report produced from this approved package.', origin }),
    result({ id: 'deployment:workspace-fingerprint', category: 'deployment', method: 'workspace_fingerprint_comparison', expected: packageData.workspace_fingerprint, actual: deploymentRecord.package?.workspace_fingerprint, passed: deploymentRecord.package?.workspace_fingerprint === packageData.workspace_fingerprint, remediation: 'Redeploy an approved package whose workspace fingerprint is recorded consistently.', origin }),
    result({ id: 'deployment:approval-checksum', category: 'deployment', method: 'approval_checksum_comparison', expected: packageData.approval_manifest_hash, actual: deploymentRecord.package?.approval_manifest_hash, passed: deploymentRecord.package?.approval_manifest_hash === packageData.approval_manifest_hash, remediation: 'Use a deployment report tied to the same approved manifest.', origin }),
    result({ id: 'deployment:preview-reference', category: 'preview', method: 'preview_metadata_comparison', expected: { id: deploymentRecord.deployment_id, timestamp: deploymentRecord.deployment_timestamp, files: deploymentRecord.uploaded_files }, actual: { id: previewReport.deployment_id, timestamp: previewReport.deployment_timestamp, files: previewReport.uploaded_files }, passed: previewReport.deployment_id === deploymentRecord.deployment_id && previewReport.deployment_timestamp === deploymentRecord.deployment_timestamp && same(previewReport.uploaded_files, deploymentRecord.uploaded_files), remediation: 'Restore the preview report emitted by this deployment.', origin }),
    result({ id: 'deployment:rollback-reference', category: 'deployment', method: 'rollback_metadata_comparison', expected: { id: deploymentRecord.deployment_id, theme: deploymentRecord.target?.theme_id, package: packageData.package_id }, actual: { id: rollback.deployment_id, theme: rollback.development_theme_id, package: rollback.deployment_package_id }, passed: rollback.deployment_id === deploymentRecord.deployment_id && String(rollback.development_theme_id) === String(deploymentRecord.target?.theme_id) && rollback.deployment_package_id === packageData.package_id && rollback.rollback_implemented === false, remediation: 'Restore rollback-preparation metadata for this exact development-theme deployment.', origin })
  ];
  let approved = null;
  try { approved = validateApprovedDeploymentPackage({ root, sessionPath }); } catch (error) { approved = { valid: false, errors: [error.message], warnings: [] }; }
  results.push(result({
    id: 'deployment:approved-chain', category: 'deployment', method: 'review_approval_generated_workspace_validation', expected: 'valid approved review, approval manifest, generated workspace, and package', actual: approved.valid ? 'valid' : approved.errors, passed: approved.valid,
    remediation: 'Resolve the recorded review, approval, generated-workspace, or manifest mismatch and create a new approved deployment package.', origin
  }));
  if (approved.valid) {
    results.push(result({
      id: 'deployment:package-integrity', category: 'checksum', method: 'stable_package_recalculation', expected: packageData, actual: approved.package, passed: same(packageData, approved.package),
      remediation: 'The saved package no longer matches current approved evidence; do not verify it as deployed. Create a new approved deployment.', origin
    }));
    results.push(result({
      id: 'deployment:manifest-checksum', category: 'checksum', method: 'sha256_manifest_comparison', expected: packageData.generated_theme_manifest_hash, actual: fileHash(path.join(root, packageData.generated_theme_manifest)), passed: fileHash(path.join(root, packageData.generated_theme_manifest)) === packageData.generated_theme_manifest_hash,
      remediation: 'Restore the generated manifest from the approved workspace or create a new deployment package.', origin
    }));
    try {
      const changes = readRequiredJson(path.join(root, packageData.change_manifest), 'Generated change manifest');
      results.push(result({
        id: 'deployment:change-manifest', category: 'deployment', method: 'generated_change_manifest_safety_validation', expected: { version: 1, source_theme_modified: false, removed_sections: 0, modified_merchant_sections: 0 }, actual: { version: changes.version, source_theme_modified: changes.safety?.source_theme_modified, removed_sections: changes.safety?.removed_sections, modified_merchant_sections: changes.safety?.modified_merchant_sections },
        passed: changes.version === 1 && changes.safety?.source_theme_modified === false && changes.safety?.removed_sections === 0 && changes.safety?.modified_merchant_sections === 0,
        remediation: 'The generated change manifest no longer represents a non-destructive deployment. Create a new approved generation.', origin
      }));
    } catch (error) {
      results.push(result({ id: 'deployment:change-manifest', category: 'deployment', method: 'generated_change_manifest_read', expected: packageData.change_manifest, actual: error.message, passed: false, remediation: 'Restore the generated change manifest from the approved workspace.', origin }));
    }
    try {
      const diff = readRequiredJson(path.join(root, packageData.theme_diff), 'Generated theme diff');
      const expectedFiles = approved.generated.manifest.generated_files.map((file) => file.path).sort();
      results.push(result({
        id: 'deployment:theme-diff', category: 'deployment', method: 'generated_theme_diff_manifest_comparison', expected: expectedFiles, actual: diff.generated_files?.slice().sort() || null,
        passed: diff.version === 1 && same(expectedFiles, diff.generated_files?.slice().sort() || []),
        remediation: 'Restore the generated theme diff from the approved workspace; it must describe the generated manifest exactly.', origin
      }));
    } catch (error) {
      results.push(result({ id: 'deployment:theme-diff', category: 'deployment', method: 'generated_theme_diff_read', expected: packageData.theme_diff, actual: error.message, passed: false, remediation: 'Restore the generated theme diff from the approved workspace.', origin }));
    }
  }
  return {
    ready: true,
    errors: [],
    warnings: [],
    deploymentPath: resolved,
    sessionPath,
    packageData,
    deploymentRecord,
    previewReport,
    rollback,
    approved,
    origin,
    snapshotDirectory: artifacts.snapshotDirectory,
    results,
    artifactReferences: {
      package: relative(root, artifacts.packagePath),
      deploymentReport: relative(root, artifacts.deploymentReportPath),
      previewReport: relative(root, artifacts.previewReportPath),
      rollback: relative(root, artifacts.rollbackPath)
    }
  };
}

module.exports = { readArtifacts, verifyDeployment };
